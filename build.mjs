// Bundles src/ into one self-contained page. Run: node build.mjs
// Output: dist/index.html (open it directly in a browser, no server needed).
// Every asset file (models, textures, sky) is embedded in the page, so it works offline from disk.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from 'node:fs';

// src/assets/manifest.js lists whatever converted asset files exist right now. Optional sets
// (for example the Mixamo characters, which are not kept in git) are simply missing from it,
// and the game falls back to the next best model.
const GROUPS = { TEX_FILES: ['tex', /\.webp$/], PROP_FILES: ['props', /\.glb$/], CHAR_FILES: ['mixamo', /\.glb$/], VEHICLE_FILES: ['vehicles', /\.glb$/], ENV_FILES: ['env', /\.(webp|hdr|jpg)$/] };
let imports = '', exports = '';
for (const [name, [dir, re]] of Object.entries(GROUPS)) {
  const path = `src/assets/${dir}`;
  // NO_ASSETS=1 leaves every new asset out, to check that the game still runs on its fallbacks
  const files = existsSync(path) && !process.env.NO_ASSETS ? readdirSync(path).filter((f) => re.test(f)).sort() : [];
  const ids = files.map((f, i) => { const id = `${dir}_${i}`; imports += `import ${id} from './${dir}/${f}';\n`; return `  '${f.replace(re, '')}': ${id},`; });
  exports += `export const ${name} = {\n${ids.join('\n')}\n};\n`;
}
writeFileSync('src/assets/manifest.js', `// Generated by build.mjs: the converted asset files that exist. Do not edit.\n${imports}${exports}`);

const result = await build({ entryPoints: ['src/main.js'], bundle: true, loader: { '.glb': 'binary', '.webp': 'binary', '.hdr': 'binary', '.jpg': 'binary' }, minify: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none' });
const js = result.outputFiles[0].text.replace(/<\/script/g, '<\\/script');
const page = readFileSync('src/page.html', 'utf8');
// asset credits travel with the page (CC BY needs the attribution wherever the work goes)
const credits = existsSync('src/assets/LICENSE.md') ? `<!--\n${readFileSync('src/assets/LICENSE.md', 'utf8').replace(/--/g, '—')}\n-->\n` : '';
const fragment = `${credits}${page}\n<script>\n${js}\n</script>\n`;
mkdirSync('dist', { recursive: true });
writeFileSync('dist/fragment.html', fragment);
writeFileSync('dist/index.html', `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body style="margin:0">\n${fragment}</body>\n</html>\n`);
const mb = statSync('dist/index.html').size / 1048576;
console.log(`built dist/index.html (${mb.toFixed(1)} MB)`);
if (mb > 60) { console.error('dist/index.html is over the 60 MB limit'); process.exit(1); }
